function normalizeInstitutionIdentifier(value: string) {
  return value.trim().toUpperCase().replace(/[^A-Z0-9]/g, "");
}

export function getInstitutionLogoAsset(code: string, name: string) {
  const normalizedCode = normalizeInstitutionIdentifier(code);
  const normalizedName = normalizeInstitutionIdentifier(name);
  const nameWords = name.toUpperCase().match(/[A-Z0-9]+/g) ?? [];
  const exactLogo = institutionLogoAssets[code.trim().toUpperCase()]
    || institutionLogoAssets[name.trim().toUpperCase()];
  if (exactLogo) return exactLogo;

  for (const [alias, asset] of institutionLogoAliases) {
    const normalizedAlias = normalizeInstitutionIdentifier(alias);
    const nameMatches = normalizedAlias.length <= 5
      ? nameWords.some((word) => normalizeInstitutionIdentifier(word) === normalizedAlias)
      : normalizedName.includes(normalizedAlias);
    if (normalizedCode.startsWith(normalizedAlias) || nameMatches) {
      return asset;
    }
  }
  return undefined;
}
